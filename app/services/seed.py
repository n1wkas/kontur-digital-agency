def seed_demo_data() -> int:
    """Заполняет пустые таблицы демонстрационными данными."""
    created = 0

    if Service.query.first() is None:
        for item in DEMO_SERVICES:
            db.session.add(
                Service(
                    title=item["title"],
                    slug=slugify(item["title"]),
                    short_description=item["short_description"],
                    description=item["description"],
                    icon_name=item["icon_name"],
                    sort_order=item["sort_order"],
                )
            )
            created += 1

    if Project.query.first() is None:
        for item in DEMO_PROJECTS:
            db.session.add(
                Project(
                    title=item["title"],
                    slug=slugify(item["title"]),
                    category=item["category"],
                    summary=item["summary"],
                    challenge=item["challenge"],
                    solution=item["solution"],
                    outcome=item["outcome"],
                    is_featured=item["is_featured"],
                )
            )
            created += 1

    if Testimonial.query.first() is None:
        for item in DEMO_TESTIMONIALS:
            db.session.add(
                Testimonial(
                    author_name=item["author_name"],
                    company_label=item["company_label"],
                    text=item["text"],
                    sort_order=item["sort_order"],
                )
            )
            created += 1

    db.session.commit()
    return created
